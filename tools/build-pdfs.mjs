#!/usr/bin/env node
/* ==========================================================================
   Builds the downloadable invitation PDFs with Chrome's own PDF engine
   (vector text, embedded fonts, correct Hindi/Bhojpuri shaping, clickable links).

     npm install          (once — installs playwright-core, uses your installed Google Chrome)
     npm run build:pdfs

   Re-run after editing js/config.js or js/translations.js. Until you do, the
   website notices the PDFs are out of date and generates cards in the browser instead.
   Set CHROME_PATH=/path/to/chrome to use a specific Chrome/Chromium binary.
   ========================================================================== */
import { chromium } from 'playwright-core';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'pdfs');
const LANGS = ['en', 'hi', 'bh'];
const JOBS = [
  { type: 'family', includeSpecial: false },
  { type: 'friends', includeSpecial: false },
];
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.png': 'image/png', '.json': 'application/json', '.pdf': 'application/pdf' };

// Tiny static server for the project folder.
const server = http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (p.endsWith('/')) p += 'index.html';
  const file = path.join(ROOT, p);
  if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}/`;

const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : { channel: 'chrome' });
fs.mkdirSync(OUT, { recursive: true });

const files = {};
let signature = null;
let problems = 0;

for (const lang of LANGS) {
  for (const job of JOBS) {
    const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
    page.on('pageerror', (e) => console.error('  page error:', e.message));
    await page.goto(base + 'index.html', { waitUntil: 'load' });
    const info = await page.evaluate((o) => window.WeddingPDF.renderForPrint(o.type, o), { ...job, lang });
    await page.waitForTimeout(300);
    const target = path.join(OUT, info.file);
    await page.pdf({ path: target, preferCSSPageSize: true, printBackground: true });
    await page.close();

    signature = info.signature;
    files[info.file.replace(/\.pdf$/, '')] = 'pdfs/' + info.file;
    const issues = info.report.filter((r) => r.overflow || r.overlaps.length);
    problems += issues.length;
    const kb = Math.round(fs.statSync(target).size / 1024);
    console.log(`${issues.length ? '⚠' : '✓'} ${info.file.padEnd(26)} ${String(kb).padStart(5)} KB  pages ${info.report.length}` +
      (issues.length ? '\n    ' + JSON.stringify(issues) : ''));
  }
}

fs.writeFileSync(path.join(OUT, 'manifest.js'),
  `/* Auto-generated by tools/build-pdfs.mjs — do not edit by hand. */\n` +
  `window.PDF_MANIFEST = ${JSON.stringify({ signature, builtAt: new Date().toISOString(), files }, null, 2)};\n`);

await browser.close();
server.close();
console.log(problems ? `\nDone with ${problems} layout warning(s).` : '\nAll PDFs built with no layout problems.');
process.exitCode = problems ? 1 : 0;
